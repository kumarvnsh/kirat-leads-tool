'use strict';
const assert=require('node:assert/strict');
const K=require('../lead-core');
const {normalizeContacts,mergeContacts,contactPrompt}=require('../lib/contacts');
const base={type:'email',value:'projects@fictional.example',source_url:'https://fictional.example/contact',source_excerpt:'Projects team: projects@fictional.example',scope:'company'};
assert.throws(()=>normalizeContacts({contacts:[{...base,verification:'verified'}]}),/cannot claim/);
assert.throws(()=>normalizeContacts({contacts:[{...base,email_status:'guess'}]}),/publicly observed/);
assert.throws(()=>normalizeContacts({contacts:[{...base,scope:'direct'}]}),/person and role/);
assert.throws(()=>normalizeContacts({contacts:[{...base,source_excerpt:''}]}),/excerpt/);
const contacts=normalizeContacts({contacts:[base,{type:'person',value:'Asha Test',role:'Projects Manager',source_url:'https://fictional.example/team',source_excerpt:'Asha Test, Projects Manager'}]},'2026-10-21').contacts;
assert.equal(contacts[0].verification,'published_only');
assert.equal(contacts[0].checked_on,'2026-10-21');
assert.equal(contacts[1].role,'Projects Manager');
assert.equal(mergeContacts(contacts,contacts).length,2);
const fixture=JSON.parse(require('node:fs').readFileSync(require('node:path').join(__dirname,'fixture-batch.json'),'utf8')).leads[0];
const lead={...fixture,id:'contact-test',notes:'Keep sales notes',status:'Contacted',contacts};
const p=K.parseEnvelope(K.backupJson([lead]));
assert(!p.fatal);assert.equal(p.rows[0].errors.length,0);
assert.deepEqual(p.rows[0].lead.contacts,contacts);
assert.equal(p.rows[0].lead.notes,'Keep sales notes');
assert(contactPrompt(lead,[]).includes('untrusted'));
console.log('contacts: public-only labels, direct association, dedupe and metadata backup round trip passed');
