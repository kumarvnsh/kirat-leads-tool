'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const { parseCsv, candidatesFromCsv, validateBatch, researchPrompt, atomicWrite } = require('../lib/research');
const { build } = require('../scripts/build');
const rows = parseCsv('company_name,website,email,email_status,personalization\r\n"Example, Co",https://example.test,a@example.test,risky,"Two\nlines ""quoted"""\r\n');
assert.equal(rows[0].company_name, 'Example, Co');
assert.equal(rows[0].personalization, 'Two\nlines "quoted"');
assert.equal(candidatesFromCsv(rows)[0].contact.email_status, 'risky');
assert.equal(candidatesFromCsv(rows)[0].qualified, false);
assert.throws(() => parseCsv('a,b\n"unfinished,x'), /Unclosed/);
assert.throws(() => parseCsv('a,a\nx,y'), /header/i);
assert.throws(() => validateBatch('{bad'), /JSON/);
assert.throws(() => validateBatch(JSON.stringify({schema_version:1,batch_date:'2026-10-21',leads:[{}]})), /Row/);
const fixture = fs.readFileSync(path.join(__dirname, 'fixture-batch.json'), 'utf8');
const validFixture = JSON.parse(fixture);
validFixture.leads = validFixture.leads.filter(l => l.evidence && l.evidence.length);
const batch = validateBatch(JSON.stringify(validFixture));
assert(batch.leads.length);
const prompt = researchPrompt(batch, [], '2026-10-21');
assert(prompt.includes(batch.leads[0].company));
assert(prompt.includes('untrusted'));
assert(prompt.includes('verification_evidence'));
assert(prompt.includes('project_evidence'));
const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'kirat-test-'));
atomicWrite(path.join(dir, 'batch.json'), fixture);
assert.equal(fs.readFileSync(path.join(dir, 'batch.json'), 'utf8'), fixture);
fs.rmSync(dir, { recursive:true });
assert.deepEqual(fs.readdirSync(build()).sort(), ['.nojekyll','assets','browser-store.js','index.html','lead-core.js']);
console.log('tool: CSV, candidates, validation, exclusions, atomic writes and deployment allowlist passed');

assert.deepEqual(fs.readdirSync(path.join(build(),'assets')).sort(), ['kirat-icon.png','kirat-logo.svg','vendor']);

assert.throws(() => require('../lib/research').validateResearchResult(JSON.stringify({schema_version:1,batch_date:'2026-10-21',leads:[],status:'blocked',reason:'Web tool unavailable'})), /Web tool unavailable/);
